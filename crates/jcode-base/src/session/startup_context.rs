        assert_eq!(original_prefix[1], rebuilt_prefix[1]);
        assert_ne!(original_prefix[2], rebuilt_prefix[2]);

        session
            .mark_startup_context_dispatched_with(&persistence)
            .expect("persist dispatch lock");
        let another = startup
            .prepare_selection(&project, 9, &preview, StartupFailurePolicy::Block)
            .expect("prepare prohibited replacement");
