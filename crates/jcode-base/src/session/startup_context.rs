/// Crash-safe session transition prepared from a complete capture.
///
/// The value is deliberately opaque to app-core. It is serializable so a
/// private recovery record can retain the exact intended transcript mutation
/// until the session target is durably committed. Raw file text exists here
/// only for that bounded recovery lifetime.
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct PreparedStartupContextSessionApply {
    schema_version: u32,
    operation_id: String,
    session_id: String,
    expected_state_sha256: String,
    mutation: PreparedStartupContextSessionMutation,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
enum PreparedStartupContextSessionMutation {
    ReplaceInitial {
        receipt: StoredStartupContextReceipt,
        startup_messages: Vec<StoredMessage>,
    },
    AppendLate {
        receipt: StoredStartupContextReceipt,
        messages: Vec<StoredMessage>,
        batch_id: String,
        file_count: usize,
    },
    ReceiptOnly {
        receipt: StoredStartupContextReceipt,
    },
}

impl PreparedStartupContextSessionApply {
    pub fn operation_id(&self) -> &str {
        &self.operation_id
    }

    pub fn batch_id(&self) -> Option<&str> {
        match &self.mutation {
            PreparedStartupContextSessionMutation::AppendLate { batch_id, .. } => Some(batch_id),
            PreparedStartupContextSessionMutation::ReplaceInitial { receipt, .. } => receipt
                .batches
                .iter()
                .find(|batch| batch.kind == StoredStartupBatchKind::Initial)
                .map(|batch| batch.id.as_str()),
            PreparedStartupContextSessionMutation::ReceiptOnly { .. } => None,
        }
    }
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum StartupContextSessionApplyOutcome {
    Applied {
        batch_id: Option<String>,
        file_count: usize,
    },
    AlreadyApplied {
        batch_id: Option<String>,
    },
    Unchanged,
}

#[derive(Debug)]
pub enum StartupContextSessionApplyError {
    DiagnosticPreparationUnsupported,
    BlockedPreparation { issue_count: usize },
    InvalidExistingReceipt { detail: String },
    InvalidPreparation { detail: String },
    SessionMismatch,
    StaleSession,
    InvalidContextProjection { detail: String },
    Persistence(anyhow::Error),
}

impl fmt::Display for StartupContextSessionApplyError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::DiagnosticPreparationUnsupported => formatter.write_str(
                "diagnostic startup preparation requires the future unattended diagnostic policy",
            ),
            Self::BlockedPreparation { issue_count } => write!(
                formatter,
                "startup selection has {issue_count} unresolved issue(s)"
            ),
            Self::InvalidExistingReceipt { detail } => {
                write!(formatter, "existing startup receipt is invalid: {detail}")
            }
            Self::InvalidPreparation { detail } => {
                write!(formatter, "startup preparation is invalid: {detail}")
            }
            Self::SessionMismatch => {
                formatter.write_str("startup apply transition belongs to a different session")
            }
            Self::StaleSession => formatter.write_str(
                "startup apply transition no longer matches the authoritative session state",
            ),
            Self::InvalidContextProjection { detail } => write!(
                formatter,
                "startup apply would invalidate the current context projection: {detail}"
            ),
            Self::Persistence(error) => {
                write!(
                    formatter,
                    "could not persist startup apply transition: {error}"
                )
            }
        }
    }
}

impl Error for StartupContextSessionApplyError {
    fn source(&self) -> Option<&(dyn Error + 'static)> {
        match self {
            Self::Persistence(error) => Some(error.as_ref()),
            _ => None,
        }
    }
}

#[derive(Debug)]
pub enum StartupContextInstallError {
    DiagnosticPreparationUnsupported,
    ReplacementLocked { state: StoredStartupContextState },
    VisibleHistory,
    InvalidExistingReceipt { detail: String },
    InvalidPreparation { detail: String },
    InvalidContextProjection { detail: String },
    Persistence(anyhow::Error),
}

impl fmt::Display for StartupContextInstallError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::DiagnosticPreparationUnsupported => formatter.write_str(
                "diagnostic startup preparation requires the future unattended diagnostic message policy",
            ),
            Self::ReplacementLocked { state } => write!(
                formatter,
                "startup context cannot be replaced after dispatch (current state: {state:?})"
            ),
            Self::VisibleHistory => formatter.write_str(
                "startup context cannot be rebuilt after visible conversation history exists",
            ),
            Self::InvalidExistingReceipt { detail } => {
                write!(formatter, "existing startup receipt is invalid: {detail}")
            }
            Self::InvalidPreparation { detail } => {
                write!(formatter, "startup preparation is invalid: {detail}")
            }
            Self::InvalidContextProjection { detail } => write!(
                formatter,
                "startup context would invalidate the current context projection: {detail}"
            ),
            Self::Persistence(error) => {
                write!(formatter, "could not persist installed startup context: {error}")
            }
        }
    }
}

impl Error for StartupContextInstallError {
    fn source(&self) -> Option<&(dyn Error + 'static)> {
        match self {
            Self::Persistence(error) => Some(error.as_ref()),
            _ => None,
        }
    }
}

