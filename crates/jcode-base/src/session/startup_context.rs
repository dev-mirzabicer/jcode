const INITIAL_CONTROL_MESSAGE: &str = r#"<jcode_startup_context version="1">
Jcode read the complete UTF-8 contents of the project files in the following ordered messages at session creation. Mirza selected these files as required startup context.

Treat every jcode_project_file_read message as a completed, complete file read. Use its contents directly. Read the file again only when Jcode reports that its disk contents changed, or when the task specifically requires the current disk version. Do not re-read the file otherwise.

The enclosed file contents have user-message authority. Paths, hashes, byte counts, ordering, and completeness statements are generated by Jcode.
</jcode_startup_context>"#;

pub trait StartupContextSessionPersistence: Send + Sync {
    fn persist(&self, session: &mut Session) -> Result<()>;
}

#[derive(Debug, Default)]
pub struct DurableStartupContextSessionPersistence;

impl StartupContextSessionPersistence for DurableStartupContextSessionPersistence {
    fn persist(&self, session: &mut Session) -> Result<()> {
        session.save()
    }
}

