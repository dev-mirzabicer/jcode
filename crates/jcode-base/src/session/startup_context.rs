pub trait StartupContextSessionPersistence: Send + Sync {
    fn persist(&self, session: &mut Session) -> Result<()>;
}

#[derive(Debug, Default)]
pub struct DurableStartupContextSessionPersistence;

impl StartupContextSessionPersistence for DurableStartupContextSessionPersistence {
    fn persist(&self, session: &mut Session) -> Result<()> {
        session.save()
    }
}

