impl Session {
    pub fn install_startup_context_block(
        &mut self,
        block: StoredStartupContextBlock,
    ) -> Result<()> {
        let previous = self.clone();
        self.startup_context = None;
        self.startup_context_block = Some(block);
        if let Err(error) = self.save() {
            *self = previous;
            return Err(error);
        }
        Ok(())
    }

    pub fn install_prepared_startup_context(
        &mut self,
        outcome: StartupPreparationOutcome,
    ) -> std::result::Result<StartupContextInstallOutcome, StartupContextInstallError> {
        self.install_prepared_startup_context_with(
            outcome,
            INITIAL_CONTROL_MESSAGE,
            &DurableStartupContextSessionPersistence,
        )
    }

    fn install_prepared_startup_context_with(
        &mut self,
        outcome: StartupPreparationOutcome,
        control_text: &str,
        persistence: &dyn StartupContextSessionPersistence,
    ) -> std::result::Result<StartupContextInstallOutcome, StartupContextInstallError> {
        if matches!(outcome, StartupPreparationOutcome::Diagnostic(_)) {
            return Err(StartupContextInstallError::DiagnosticPreparationUnsupported);
        }
        if let Some(receipt) = self.startup_context.as_ref()
            && matches!(
                receipt.state,
                StoredStartupContextState::Dispatched
                    | StoredStartupContextState::ProviderAccepted
                    | StoredStartupContextState::MetadataRepair { .. }
            )
        {
            return Err(StartupContextInstallError::ReplacementLocked {
                state: receipt.state.clone(),
            });
        }
        if self.messages.iter().any(is_visible_conversation_message) {
            return Err(StartupContextInstallError::VisibleHistory);
        }
        validate_existing_receipt_references(self)?;

        let previous = self.clone();
        let prior_receipt = self.startup_context.as_ref();
        let (receipt, startup_messages) =
            build_initial_receipt(outcome, prior_receipt, control_text, Utc::now())?;
        let prior_message_ids = startup_message_ids(prior_receipt);
        let retained_hidden_messages = self
            .messages
            .iter()
            .filter(|message| {
                !prior_message_ids.contains(message.id.as_str())
                    && !is_session_context_stored_message(message)
            })
            .cloned()
            .collect::<Vec<_>>();

        self.startup_context = Some(receipt);
        self.startup_context_block = None;
        self.replace_messages(startup_messages);
        self.ensure_initial_session_context_message_after_startup();
        for message in retained_hidden_messages {
            self.append_stored_message(message);
        }

        if let Err(error) = jcode_context_core::project_context(&self.messages, &self.context_view)
        {
            *self = previous;
            return Err(StartupContextInstallError::InvalidContextProjection {
                detail: error.to_string(),
            });
        }
        if let Err(error) = persistence.persist(self) {
            *self = previous;
            return Err(StartupContextInstallError::Persistence(error));
        }

        let accounting = self.startup_context_accounting();
        Ok(StartupContextInstallOutcome {
            state: accounting
                .state
                .expect("installed startup receipt has aggregate state"),
            file_count: accounting.file_count,
            captured_bytes: accounting.captured_bytes,
            estimated_tokens: accounting.estimated_tokens,
        })
    }

    pub fn prepare_startup_context_session_apply(
        &self,
        operation_id: &str,
        outcome: StartupPreparationOutcome,
    ) -> std::result::Result<PreparedStartupContextSessionApply, StartupContextSessionApplyError>
    {
        self.prepare_startup_context_session_apply_with(
            operation_id,
            outcome,
            INITIAL_CONTROL_MESSAGE,
            LATE_UPDATE_CONTROL_MESSAGE,
        )
    }

    fn prepare_startup_context_session_apply_with(
        &self,
        operation_id: &str,
        outcome: StartupPreparationOutcome,
        initial_control_text: &str,
        late_control_text: &str,
    ) -> std::result::Result<PreparedStartupContextSessionApply, StartupContextSessionApplyError>
    {
        if operation_id.trim().is_empty() {
            return Err(StartupContextSessionApplyError::InvalidPreparation {
                detail: "apply operation ID is empty".to_string(),
            });
        }
        let preparation = match outcome {
            StartupPreparationOutcome::Ready(preparation) => preparation,
            StartupPreparationOutcome::Blocked(preparation) => {
                return Err(StartupContextSessionApplyError::BlockedPreparation {
                    issue_count: preparation.issue_count(),
                });
            }
            StartupPreparationOutcome::Diagnostic(_) => {
                return Err(StartupContextSessionApplyError::DiagnosticPreparationUnsupported);
            }
        };
        validate_existing_receipt_references(self).map_err(map_install_to_apply_error)?;

        let expected_state_sha256 = startup_apply_state_sha256(self)?;
        let now = Utc::now();
        let mutation = match self.startup_context.as_ref() {
            Some(receipt)
                if matches!(
                    receipt.state,
                    StoredStartupContextState::Dispatched
                        | StoredStartupContextState::ProviderAccepted
                        | StoredStartupContextState::MetadataRepair { .. }
                ) =>
            {
                build_late_apply_mutation(
                    receipt,
                    operation_id,
                    preparation,
                    late_control_text,
                    now,
                )?
            }
            prior_receipt => {
                if self.messages.iter().any(is_visible_conversation_message) {
                    return Err(StartupContextSessionApplyError::InvalidPreparation {
                        detail: "initial startup context cannot be rebuilt after visible conversation history exists"
                            .to_string(),
                    });
                }
                let (mut receipt, startup_messages) = build_initial_receipt(
                    StartupPreparationOutcome::Ready(preparation),
                    prior_receipt,
                    initial_control_text,
                    now,
                )
                .map_err(map_install_to_apply_error)?;
                receipt.last_apply_operation_id = Some(operation_id.to_string());
                receipt
                    .pending_updates
                    .retain(|pending| pending.operation_id != operation_id);
                PreparedStartupContextSessionMutation::ReplaceInitial {
                    receipt,
                    startup_messages,
                }
            }
        };

        Ok(PreparedStartupContextSessionApply {
            schema_version: 1,
            operation_id: operation_id.to_string(),
            session_id: self.id.clone(),
            expected_state_sha256,
            mutation,
        })
    }

    pub fn apply_prepared_startup_context_session(
        &mut self,
        transition: &PreparedStartupContextSessionApply,
    ) -> std::result::Result<StartupContextSessionApplyOutcome, StartupContextSessionApplyError>
    {
        self.apply_prepared_startup_context_session_with(
            transition,
            &DurableStartupContextSessionPersistence,
        )
    }

    pub fn apply_prepared_startup_context_session_with(
        &mut self,
        transition: &PreparedStartupContextSessionApply,
        persistence: &dyn StartupContextSessionPersistence,
    ) -> std::result::Result<StartupContextSessionApplyOutcome, StartupContextSessionApplyError>
    {
        if transition.schema_version != 1 {
            return Err(StartupContextSessionApplyError::InvalidPreparation {
                detail: format!(
                    "unsupported prepared apply schema version {}",
                    transition.schema_version
                ),
            });
        }
        if transition.session_id != self.id {
            return Err(StartupContextSessionApplyError::SessionMismatch);
        }
        if self.startup_context.as_ref().is_some_and(|receipt| {
            receipt.last_apply_operation_id.as_deref() == Some(transition.operation_id())
        }) {
            if matches!(
                &transition.mutation,
                PreparedStartupContextSessionMutation::ReceiptOnly { .. }
            ) {
                return Ok(StartupContextSessionApplyOutcome::Unchanged);
            }
            return Ok(StartupContextSessionApplyOutcome::AlreadyApplied {
                batch_id: transition.batch_id().map(ToOwned::to_owned),
            });
        }
        if startup_apply_state_sha256(self)? != transition.expected_state_sha256 {
            return Err(StartupContextSessionApplyError::StaleSession);
        }
        validate_existing_receipt_references(self).map_err(map_install_to_apply_error)?;

        let previous = self.clone();
        let (batch_id, file_count, unchanged) = match &transition.mutation {
            PreparedStartupContextSessionMutation::ReplaceInitial {
                receipt,
                startup_messages,
            } => {
                let prior_message_ids = startup_message_ids(self.startup_context.as_ref());
                let retained_hidden_messages = self
                    .messages
                    .iter()
                    .filter(|message| {
                        !prior_message_ids.contains(message.id.as_str())
                            && !is_session_context_stored_message(message)
                    })
                    .cloned()
                    .collect::<Vec<_>>();
                self.startup_context = Some(receipt.clone());
                self.replace_messages(startup_messages.clone());
                self.ensure_initial_session_context_message_after_startup();
                for message in retained_hidden_messages {
                    self.append_stored_message(message);
                }
                (
                    receipt
                        .batches
                        .iter()
                        .find(|batch| batch.kind == StoredStartupBatchKind::Initial)
                        .map(|batch| batch.id.clone()),
                    receipt
                        .batches
                        .iter()
                        .find(|batch| batch.kind == StoredStartupBatchKind::Initial)
                        .map_or(0, |batch| batch.files.len()),
                    false,
                )
            }
            PreparedStartupContextSessionMutation::AppendLate {
                receipt,
                messages,
                batch_id,
                file_count,
            } => {
                self.startup_context = Some(receipt.clone());
                for message in messages {
                    self.append_stored_message(message.clone());
                }
                (Some(batch_id.clone()), *file_count, false)
            }
            PreparedStartupContextSessionMutation::ReceiptOnly { receipt } => {
                self.startup_context = Some(receipt.clone());
                (None, 0, true)
            }
        };
        self.startup_context_block = None;

        if let Err(error) = jcode_context_core::project_context(&self.messages, &self.context_view)
        {
            *self = previous;
            return Err(StartupContextSessionApplyError::InvalidContextProjection {
                detail: error.to_string(),
            });
        }
        if let Err(error) = persistence.persist(self) {
            *self = previous;
            return Err(StartupContextSessionApplyError::Persistence(error));
        }

        if unchanged {
            Ok(StartupContextSessionApplyOutcome::Unchanged)
        } else {
            Ok(StartupContextSessionApplyOutcome::Applied {
                batch_id,
                file_count,
            })
        }
    }

    pub fn mark_startup_context_dispatched(
        &mut self,
    ) -> std::result::Result<StartupContextDispatchOutcome, StartupContextDispatchError> {
        self.mark_startup_context_dispatched_with(&DurableStartupContextSessionPersistence)
    }

    pub fn mark_startup_context_dispatched_with(
        &mut self,
        persistence: &dyn StartupContextSessionPersistence,
    ) -> std::result::Result<StartupContextDispatchOutcome, StartupContextDispatchError> {
        if self.startup_context_block.is_some() {
            return Err(StartupContextDispatchError::Blocked);
        }
        let Some(receipt) = self.startup_context.as_mut() else {
            return Ok(StartupContextDispatchOutcome::NotApplicable);
        };
        if matches!(receipt.state, StoredStartupContextState::Blocked) {
            return Err(StartupContextDispatchError::Blocked);
        }

        let previous_receipt = receipt.clone();
        let previous_updated_at = self.updated_at;
        let previous_persist_state = self.persist_state.clone();
        let now = Utc::now();
        let mut changed = false;
        let mut batches_marked = 0usize;

        if matches!(
            receipt.state,
            StoredStartupContextState::Empty | StoredStartupContextState::Prepared
        ) {
            receipt.state = StoredStartupContextState::Dispatched;
            receipt.first_dispatched_at.get_or_insert(now);
            changed = true;
        }
        for batch in &mut receipt.batches {
            if batch.delivery_state == StoredStartupBatchDeliveryState::Captured {
                batch.delivery_state = StoredStartupBatchDeliveryState::Dispatched;
                batch.first_dispatched_at.get_or_insert(now);
                batches_marked = batches_marked.saturating_add(1);
                changed = true;
            }
        }
        if !changed {
            return Ok(StartupContextDispatchOutcome::Unchanged);
        }

        if let Err(error) = persistence.persist(self) {
            self.startup_context = Some(previous_receipt);
            self.updated_at = previous_updated_at;
            self.persist_state = previous_persist_state;
            return Err(StartupContextDispatchError::Persistence(error));
        }

        Ok(StartupContextDispatchOutcome::Persisted { batches_marked })
    }

    pub fn mark_startup_context_provider_accepted(&mut self) -> StartupContextAcceptanceOutcome {
        self.mark_startup_context_provider_accepted_with(&DurableStartupContextSessionPersistence)
    }

    pub fn mark_startup_context_provider_accepted_with(
        &mut self,
        persistence: &dyn StartupContextSessionPersistence,
    ) -> StartupContextAcceptanceOutcome {
        let Some(receipt) = self.startup_context.as_mut() else {
            return StartupContextAcceptanceOutcome::NotApplicable;
        };
        let now = Utc::now();
        let mut changed = false;
        let mut batches_marked = 0usize;

        if matches!(receipt.state, StoredStartupContextState::Dispatched) {
            receipt.state = StoredStartupContextState::ProviderAccepted;
            receipt.first_provider_accepted_at.get_or_insert(now);
            changed = true;
        }
        for batch in &mut receipt.batches {
            if batch.delivery_state == StoredStartupBatchDeliveryState::Dispatched {
                batch.delivery_state = StoredStartupBatchDeliveryState::ProviderAccepted;
                batch.first_provider_accepted_at.get_or_insert(now);
                batches_marked = batches_marked.saturating_add(1);
                changed = true;
            }
        }
        if !changed {
            return StartupContextAcceptanceOutcome::Unchanged;
        }

        receipt.metadata_repair = None;
        if let Err(error) = persistence.persist(self) {
            let error = error.to_string();
            let receipt = self
                .startup_context
                .as_mut()
                .expect("startup receipt remains installed after acceptance save failure");
            receipt.state = StoredStartupContextState::MetadataRepair {
                target: StoredStartupMetadataRepairTarget::ProviderAccepted,
            };
            receipt.metadata_repair = Some(StoredStartupMetadataRepair {
                target: StoredStartupMetadataRepairTarget::ProviderAccepted,
                required_at: now,
                attempts: 1,
                last_error: error.clone(),
            });
            return StartupContextAcceptanceOutcome::MetadataRepairRequired { error };
        }

        StartupContextAcceptanceOutcome::Persisted { batches_marked }
    }

    pub fn retry_startup_context_metadata_repair(&mut self) -> StartupContextRepairOutcome {
        self.retry_startup_context_metadata_repair_with(&DurableStartupContextSessionPersistence)
    }

    pub fn retry_startup_context_metadata_repair_with(
        &mut self,
        persistence: &dyn StartupContextSessionPersistence,
    ) -> StartupContextRepairOutcome {
        let Some(receipt) = self.startup_context.as_mut() else {
            return StartupContextRepairOutcome::NotNeeded;
        };
        let Some(mut repair) = receipt.metadata_repair.take() else {
            return StartupContextRepairOutcome::NotNeeded;
        };
        receipt.state = match repair.target {
            StoredStartupMetadataRepairTarget::ProviderAccepted => {
                StoredStartupContextState::ProviderAccepted
            }
        };

        if let Err(error) = persistence.persist(self) {
            let error = error.to_string();
            repair.attempts = repair.attempts.saturating_add(1);
            repair.last_error.clone_from(&error);
            let receipt = self
                .startup_context
                .as_mut()
                .expect("startup receipt remains installed during metadata repair");
            receipt.state = StoredStartupContextState::MetadataRepair {
                target: repair.target,
            };
            receipt.metadata_repair = Some(repair);
            return StartupContextRepairOutcome::StillRequired { error };
        }

        StartupContextRepairOutcome::Persisted
    }

    pub fn startup_context_accounting(&self) -> StartupContextAccounting {
        let Some(receipt) = self.startup_context.as_ref() else {
            return StartupContextAccounting::default();
        };
        let (file_count, captured_bytes, estimated_tokens) = receipt
            .batches
            .iter()
            .flat_map(|batch| batch.files.iter())
            .fold((0usize, 0u64, 0u64), |(count, bytes, tokens), file| {
                (
                    count.saturating_add(1),
                    bytes.saturating_add(file.bytes),
                    tokens.saturating_add(file.estimated_tokens),
                )
            });
        StartupContextAccounting {
            state: Some(receipt.state.clone()),
            file_count,
            captured_bytes,
            estimated_tokens,
            batch_delivery: receipt
                .batches
                .iter()
                .map(|batch| batch.delivery_state)
                .collect(),
            blocked_issue_count: receipt.blocked_issues.len(),
            pending_update_count: receipt.pending_updates.len(),
        }
    }
}

fn build_late_apply_mutation(
    receipt: &StoredStartupContextReceipt,
    operation_id: &str,
    preparation: StartupPreparation,
    control_text: &str,
    now: DateTime<Utc>,
) -> std::result::Result<PreparedStartupContextSessionMutation, StartupContextSessionApplyError> {
    let prepared_project = preparation
        .project()
        .key()
        .to_stored()
        .map_err(invalid_apply_preparation)?;
    if prepared_project != receipt.project {
        return Err(StartupContextSessionApplyError::InvalidPreparation {
            detail: "captured selection belongs to a different project than the session receipt"
                .to_string(),
        });
    }

    let existing_spec_ids = receipt
        .batches
        .iter()
        .flat_map(|batch| batch.files.iter())
        .map(|file| file.spec_id.as_str())
        .collect::<HashSet<_>>();
    let additions = preparation
        .captured_files()
        .filter(|file| !existing_spec_ids.contains(file.spec_id().as_str()))
        .collect::<Vec<_>>();
    let mut next_receipt = receipt.clone();
    next_receipt.plan_revision = preparation.plan_revision();
    next_receipt.last_apply_operation_id = Some(operation_id.to_string());
    next_receipt
        .pending_updates
        .retain(|pending| pending.operation_id != operation_id);
    if additions.is_empty() {
        return Ok(PreparedStartupContextSessionMutation::ReceiptOnly {
            receipt: next_receipt,
        });
    }

    let batch_id = crate::id::new_id("startup-batch");
    let control_message_id = crate::id::new_id("message");
    let mut messages = vec![startup_stored_message(
        control_message_id.clone(),
        vec![ContentBlock::Text {
            text: control_text.to_string(),
            cache_control: None,
        }],
    )];
    let mut files = Vec::with_capacity(additions.len());
    for (index, file) in additions.iter().enumerate() {
        let ordinal = u32::try_from(index.saturating_add(2)).map_err(|_| {
            StartupContextSessionApplyError::InvalidPreparation {
                detail: "late startup file ordinal exceeded the durable u32 range".to_string(),
            }
        })?;
        let message_id = crate::id::new_id("message");
        let logical_path = startup_utf8_path(file.logical_path(), "logical path")
            .map_err(map_install_to_apply_error)?;
        let resolved_path = startup_utf8_path(file.resolved_path(), "resolved path")
            .map_err(map_install_to_apply_error)?;
        messages.push(startup_stored_message(
            message_id.clone(),
            vec![
                ContentBlock::Text {
                    text: startup_file_metadata(
                        ordinal,
                        &logical_path,
                        &resolved_path,
                        file.sha256(),
                        file.bytes(),
                    ),
                    cache_control: None,
                },
                ContentBlock::Text {
                    text: file.text().to_string(),
                    cache_control: None,
                },
            ],
        ));
        files.push(stored_file_receipt(
            file,
            message_id,
            ordinal,
            logical_path,
            resolved_path,
            now,
        ));
    }
    let file_count = files.len();
    next_receipt.batches.push(StoredStartupContextBatch {
        id: batch_id.clone(),
        kind: StoredStartupBatchKind::Late,
        control_message_id,
        files,
        appended_at: now,
        delivery_state: StoredStartupBatchDeliveryState::Captured,
        first_dispatched_at: None,
        first_provider_accepted_at: None,
    });
    Ok(PreparedStartupContextSessionMutation::AppendLate {
        receipt: next_receipt,
        messages,
        batch_id,
        file_count,
    })
}

fn startup_apply_state_sha256(
    session: &Session,
) -> std::result::Result<String, StartupContextSessionApplyError> {
    let bytes = serde_json::to_vec(&(
        &session.messages,
        &session.context_view,
        &session.startup_context,
        &session.startup_context_block,
    ))
    .map_err(
        |error| StartupContextSessionApplyError::InvalidExistingReceipt {
            detail: format!("could not fingerprint authoritative session state: {error}"),
        },
    )?;
    Ok(format!("{:x}", Sha256::digest(bytes)))
}

fn invalid_apply_preparation(error: StartupContextError) -> StartupContextSessionApplyError {
    StartupContextSessionApplyError::InvalidPreparation {
        detail: error.to_string(),
    }
}

fn map_install_to_apply_error(
    error: StartupContextInstallError,
) -> StartupContextSessionApplyError {
    match error {
        StartupContextInstallError::DiagnosticPreparationUnsupported => {
            StartupContextSessionApplyError::DiagnosticPreparationUnsupported
        }
        StartupContextInstallError::InvalidExistingReceipt { detail } => {
            StartupContextSessionApplyError::InvalidExistingReceipt { detail }
        }
        StartupContextInstallError::InvalidPreparation { detail } => {
            StartupContextSessionApplyError::InvalidPreparation { detail }
        }
        StartupContextInstallError::InvalidContextProjection { detail } => {
            StartupContextSessionApplyError::InvalidContextProjection { detail }
        }
        StartupContextInstallError::Persistence(error) => {
            StartupContextSessionApplyError::Persistence(error)
        }
        StartupContextInstallError::ReplacementLocked { state } => {
            StartupContextSessionApplyError::InvalidPreparation {
                detail: format!("startup replacement is locked in state {state:?}"),
            }
        }
        StartupContextInstallError::VisibleHistory => {
            StartupContextSessionApplyError::InvalidPreparation {
                detail: "startup replacement has visible history".to_string(),
            }
        }
    }
}

fn build_initial_receipt(
    outcome: StartupPreparationOutcome,
    prior_receipt: Option<&StoredStartupContextReceipt>,
    control_text: &str,
    now: DateTime<Utc>,
) -> std::result::Result<
    (StoredStartupContextReceipt, Vec<StoredMessage>),
    StartupContextInstallError,
> {
    let blocked = matches!(outcome, StartupPreparationOutcome::Blocked(_));
    let preparation = outcome.into_preparation();
    let project = preparation
        .project()
        .key()
        .to_stored()
        .map_err(invalid_preparation)?;
    let blocked_issues = preparation
        .issues()
        .map(|issue| issue.to_stored().map_err(invalid_preparation))
        .collect::<std::result::Result<Vec<_>, _>>()?;
    let captured = preparation.captured_files().collect::<Vec<_>>();
    let mut messages = Vec::with_capacity(captured.len().saturating_add(2));
    let mut batches = Vec::new();

    if !captured.is_empty() {
        let prior_batch = prior_receipt.and_then(|receipt| {
            receipt
                .batches
                .iter()
                .find(|batch| batch.kind == StoredStartupBatchKind::Initial)
        });
        let control_message_id = prior_batch
            .map(|batch| batch.control_message_id.clone())
            .unwrap_or_else(|| crate::id::new_id("message"));
        messages.push(startup_stored_message(
            control_message_id.clone(),
            vec![ContentBlock::Text {
                text: control_text.to_string(),
                cache_control: None,
            }],
        ));

        let prior_files = prior_batch
            .map(|batch| {
                batch
                    .files
                    .iter()
                    .map(|file| (file.spec_id.as_str(), file.message_id.as_str()))
                    .collect::<HashMap<_, _>>()
            })
            .unwrap_or_default();
        let mut file_receipts = Vec::with_capacity(captured.len());
        for (index, file) in captured.into_iter().enumerate() {
            let ordinal = u32::try_from(index.saturating_add(2)).map_err(|_| {
                StartupContextInstallError::InvalidPreparation {
                    detail: "startup file ordinal exceeded the durable u32 range".to_string(),
                }
            })?;
            let message_id = prior_files
                .get(file.spec_id().as_str())
                .map(|id| (*id).to_string())
                .unwrap_or_else(|| crate::id::new_id("message"));
            let logical_path = startup_utf8_path(file.logical_path(), "logical path")?;
            let resolved_path = startup_utf8_path(file.resolved_path(), "resolved path")?;
            let metadata = startup_file_metadata(
                ordinal,
                &logical_path,
                &resolved_path,
                file.sha256(),
                file.bytes(),
            );
            messages.push(startup_stored_message(
                message_id.clone(),
                vec![
                    ContentBlock::Text {
                        text: metadata,
                        cache_control: None,
                    },
                    ContentBlock::Text {
                        text: file.text().to_string(),
                        cache_control: None,
                    },
                ],
            ));
            file_receipts.push(stored_file_receipt(
                file,
                message_id,
                ordinal,
                logical_path,
                resolved_path,
                now,
            ));
        }

        batches.push(StoredStartupContextBatch {
            id: prior_batch
                .map(|batch| batch.id.clone())
                .unwrap_or_else(|| crate::id::new_id("startup-batch")),
            kind: StoredStartupBatchKind::Initial,
            control_message_id,
            files: file_receipts,
            appended_at: now,
            delivery_state: StoredStartupBatchDeliveryState::Captured,
            first_dispatched_at: None,
            first_provider_accepted_at: None,
        });
    }

    let state = if blocked {
        StoredStartupContextState::Blocked
    } else if batches.is_empty() {
        StoredStartupContextState::Empty
    } else {
        StoredStartupContextState::Prepared
    };
    Ok((
        StoredStartupContextReceipt {
            schema_version: STARTUP_CONTEXT_RECEIPT_SCHEMA_VERSION,
            project,
            plan_revision: preparation.plan_revision(),
            state,
            batches,
            blocked_issues,
            pending_updates: Vec::new(),
            last_apply_operation_id: None,
            prepared_at: now,
            first_dispatched_at: None,
            first_provider_accepted_at: None,
            metadata_repair: None,
        },
        messages,
    ))
}

