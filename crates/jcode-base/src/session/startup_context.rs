impl Session {
    pub fn install_prepared_startup_context(
        &mut self,
        outcome: StartupPreparationOutcome,
    ) -> std::result::Result<StartupContextInstallOutcome, StartupContextInstallError> {
        self.install_prepared_startup_context_with(
            outcome,
            INITIAL_CONTROL_MESSAGE,
            &DurableStartupContextSessionPersistence,
        )
    }

    fn install_prepared_startup_context_with(
        &mut self,
        outcome: StartupPreparationOutcome,
        control_text: &str,
        persistence: &dyn StartupContextSessionPersistence,
    ) -> std::result::Result<StartupContextInstallOutcome, StartupContextInstallError> {
        if matches!(outcome, StartupPreparationOutcome::Diagnostic(_)) {
            return Err(StartupContextInstallError::DiagnosticPreparationUnsupported);
        }
        if let Some(receipt) = self.startup_context.as_ref()
            && matches!(
                receipt.state,
                StoredStartupContextState::Dispatched
                    | StoredStartupContextState::ProviderAccepted
                    | StoredStartupContextState::MetadataRepair { .. }
            )
        {
            return Err(StartupContextInstallError::ReplacementLocked {
                state: receipt.state.clone(),
            });
        }
        if self.messages.iter().any(is_visible_conversation_message) {
            return Err(StartupContextInstallError::VisibleHistory);
        }
        validate_existing_receipt_references(self)?;

        let previous = self.clone();
        let prior_receipt = self.startup_context.as_ref();
        let (receipt, startup_messages) =
            build_initial_receipt(outcome, prior_receipt, control_text, Utc::now())?;
        let prior_message_ids = startup_message_ids(prior_receipt);
        let retained_hidden_messages = self
            .messages
            .iter()
            .filter(|message| {
                !prior_message_ids.contains(message.id.as_str())
                    && !is_session_context_stored_message(message)
            })
            .cloned()
            .collect::<Vec<_>>();

        self.startup_context = Some(receipt);
        self.replace_messages(startup_messages);
        self.ensure_initial_session_context_message_after_startup();
        for message in retained_hidden_messages {
            self.append_stored_message(message);
        }

        if let Err(error) = jcode_context_core::project_context(&self.messages, &self.context_view)
        {
            *self = previous;
            return Err(StartupContextInstallError::InvalidContextProjection {
                detail: error.to_string(),
            });
        }
        if let Err(error) = persistence.persist(self) {
            *self = previous;
            return Err(StartupContextInstallError::Persistence(error));
        }

        let accounting = self.startup_context_accounting();
        Ok(StartupContextInstallOutcome {
            state: accounting
                .state
                .expect("installed startup receipt has aggregate state"),
            file_count: accounting.file_count,
            captured_bytes: accounting.captured_bytes,
            estimated_tokens: accounting.estimated_tokens,
        })
    }

    pub fn mark_startup_context_dispatched(
        &mut self,
    ) -> std::result::Result<StartupContextDispatchOutcome, StartupContextDispatchError> {
        self.mark_startup_context_dispatched_with(&DurableStartupContextSessionPersistence)
    }

    pub fn mark_startup_context_dispatched_with(
        &mut self,
        persistence: &dyn StartupContextSessionPersistence,
    ) -> std::result::Result<StartupContextDispatchOutcome, StartupContextDispatchError> {
        let Some(receipt) = self.startup_context.as_mut() else {
            return Ok(StartupContextDispatchOutcome::NotApplicable);
        };
        if matches!(receipt.state, StoredStartupContextState::Blocked) {
            return Err(StartupContextDispatchError::Blocked);
        }

        let previous_receipt = receipt.clone();
        let previous_updated_at = self.updated_at;
        let previous_persist_state = self.persist_state.clone();
        let now = Utc::now();
        let mut changed = false;
        let mut batches_marked = 0usize;

        if matches!(
            receipt.state,
            StoredStartupContextState::Empty | StoredStartupContextState::Prepared
        ) {
            receipt.state = StoredStartupContextState::Dispatched;
            receipt.first_dispatched_at.get_or_insert(now);
            changed = true;
        }
        for batch in &mut receipt.batches {
            if batch.delivery_state == StoredStartupBatchDeliveryState::Captured {
                batch.delivery_state = StoredStartupBatchDeliveryState::Dispatched;
                batch.first_dispatched_at.get_or_insert(now);
                batches_marked = batches_marked.saturating_add(1);
                changed = true;
            }
        }
        if !changed {
            return Ok(StartupContextDispatchOutcome::Unchanged);
        }

        if let Err(error) = persistence.persist(self) {
            self.startup_context = Some(previous_receipt);
            self.updated_at = previous_updated_at;
            self.persist_state = previous_persist_state;
            return Err(StartupContextDispatchError::Persistence(error));
        }

        Ok(StartupContextDispatchOutcome::Persisted { batches_marked })
    }

    pub fn mark_startup_context_provider_accepted(&mut self) -> StartupContextAcceptanceOutcome {
        self.mark_startup_context_provider_accepted_with(&DurableStartupContextSessionPersistence)
    }

    pub fn mark_startup_context_provider_accepted_with(
        &mut self,
        persistence: &dyn StartupContextSessionPersistence,
    ) -> StartupContextAcceptanceOutcome {
        let Some(receipt) = self.startup_context.as_mut() else {
            return StartupContextAcceptanceOutcome::NotApplicable;
        };
        let now = Utc::now();
        let mut changed = false;
        let mut batches_marked = 0usize;

        if matches!(receipt.state, StoredStartupContextState::Dispatched) {
            receipt.state = StoredStartupContextState::ProviderAccepted;
            receipt.first_provider_accepted_at.get_or_insert(now);
            changed = true;
        }
        for batch in &mut receipt.batches {
            if batch.delivery_state == StoredStartupBatchDeliveryState::Dispatched {
                batch.delivery_state = StoredStartupBatchDeliveryState::ProviderAccepted;
                batch.first_provider_accepted_at.get_or_insert(now);
                batches_marked = batches_marked.saturating_add(1);
                changed = true;
            }
        }
        if !changed {
            return StartupContextAcceptanceOutcome::Unchanged;
        }

        receipt.metadata_repair = None;
        if let Err(error) = persistence.persist(self) {
            let error = error.to_string();
            let receipt = self
                .startup_context
                .as_mut()
                .expect("startup receipt remains installed after acceptance save failure");
            receipt.state = StoredStartupContextState::MetadataRepair {
                target: StoredStartupMetadataRepairTarget::ProviderAccepted,
            };
            receipt.metadata_repair = Some(StoredStartupMetadataRepair {
                target: StoredStartupMetadataRepairTarget::ProviderAccepted,
                required_at: now,
                attempts: 1,
                last_error: error.clone(),
            });
            return StartupContextAcceptanceOutcome::MetadataRepairRequired { error };
        }

        StartupContextAcceptanceOutcome::Persisted { batches_marked }
    }

    pub fn retry_startup_context_metadata_repair(&mut self) -> StartupContextRepairOutcome {
        self.retry_startup_context_metadata_repair_with(&DurableStartupContextSessionPersistence)
    }

    pub fn retry_startup_context_metadata_repair_with(
        &mut self,
        persistence: &dyn StartupContextSessionPersistence,
    ) -> StartupContextRepairOutcome {
        let Some(receipt) = self.startup_context.as_mut() else {
            return StartupContextRepairOutcome::NotNeeded;
        };
        let Some(mut repair) = receipt.metadata_repair.take() else {
            return StartupContextRepairOutcome::NotNeeded;
        };
        receipt.state = match repair.target {
            StoredStartupMetadataRepairTarget::ProviderAccepted => {
                StoredStartupContextState::ProviderAccepted
            }
        };

        if let Err(error) = persistence.persist(self) {
            let error = error.to_string();
            repair.attempts = repair.attempts.saturating_add(1);
            repair.last_error.clone_from(&error);
            let receipt = self
                .startup_context
                .as_mut()
                .expect("startup receipt remains installed during metadata repair");
            receipt.state = StoredStartupContextState::MetadataRepair {
                target: repair.target,
            };
            receipt.metadata_repair = Some(repair);
            return StartupContextRepairOutcome::StillRequired { error };
        }

        StartupContextRepairOutcome::Persisted
    }

    pub fn startup_context_accounting(&self) -> StartupContextAccounting {
        let Some(receipt) = self.startup_context.as_ref() else {
            return StartupContextAccounting::default();
        };
        let (file_count, captured_bytes, estimated_tokens) = receipt
            .batches
            .iter()
            .flat_map(|batch| batch.files.iter())
            .fold((0usize, 0u64, 0u64), |(count, bytes, tokens), file| {
                (
                    count.saturating_add(1),
                    bytes.saturating_add(file.bytes),
                    tokens.saturating_add(file.estimated_tokens),
                )
            });
        StartupContextAccounting {
            state: Some(receipt.state.clone()),
            file_count,
            captured_bytes,
            estimated_tokens,
            batch_delivery: receipt
                .batches
                .iter()
                .map(|batch| batch.delivery_state)
                .collect(),
            blocked_issue_count: receipt.blocked_issues.len(),
            pending_update_count: receipt.pending_updates.len(),
        }
    }
}

fn build_initial_receipt(
    outcome: StartupPreparationOutcome,
    prior_receipt: Option<&StoredStartupContextReceipt>,
    control_text: &str,
    now: DateTime<Utc>,
) -> std::result::Result<
    (StoredStartupContextReceipt, Vec<StoredMessage>),
    StartupContextInstallError,
> {
    let blocked = matches!(outcome, StartupPreparationOutcome::Blocked(_));
    let preparation = outcome.into_preparation();
    let project = preparation
        .project()
        .key()
        .to_stored()
        .map_err(invalid_preparation)?;
    let blocked_issues = preparation
        .issues()
        .map(|issue| issue.to_stored().map_err(invalid_preparation))
        .collect::<std::result::Result<Vec<_>, _>>()?;
    let captured = preparation.captured_files().collect::<Vec<_>>();
    let mut messages = Vec::with_capacity(captured.len().saturating_add(2));
    let mut batches = Vec::new();

    if !captured.is_empty() {
        let prior_batch = prior_receipt.and_then(|receipt| {
            receipt
                .batches
                .iter()
                .find(|batch| batch.kind == StoredStartupBatchKind::Initial)
        });
        let control_message_id = prior_batch
            .map(|batch| batch.control_message_id.clone())
            .unwrap_or_else(|| crate::id::new_id("message"));
        messages.push(startup_stored_message(
            control_message_id.clone(),
            vec![ContentBlock::Text {
                text: control_text.to_string(),
                cache_control: None,
            }],
        ));

        let prior_files = prior_batch
            .map(|batch| {
                batch
                    .files
                    .iter()
                    .map(|file| (file.spec_id.as_str(), file.message_id.as_str()))
                    .collect::<HashMap<_, _>>()
            })
            .unwrap_or_default();
        let mut file_receipts = Vec::with_capacity(captured.len());
        for (index, file) in captured.into_iter().enumerate() {
            let ordinal = u32::try_from(index.saturating_add(2)).map_err(|_| {
                StartupContextInstallError::InvalidPreparation {
                    detail: "startup file ordinal exceeded the durable u32 range".to_string(),
                }
            })?;
            let message_id = prior_files
                .get(file.spec_id().as_str())
                .map(|id| (*id).to_string())
                .unwrap_or_else(|| crate::id::new_id("message"));
            let logical_path = startup_utf8_path(file.logical_path(), "logical path")?;
            let resolved_path = startup_utf8_path(file.resolved_path(), "resolved path")?;
            let metadata = startup_file_metadata(
                ordinal,
                &logical_path,
                &resolved_path,
                file.sha256(),
                file.bytes(),
            );
            messages.push(startup_stored_message(
                message_id.clone(),
                vec![
                    ContentBlock::Text {
                        text: metadata,
                        cache_control: None,
                    },
                    ContentBlock::Text {
                        text: file.text().to_string(),
                        cache_control: None,
                    },
                ],
            ));
            file_receipts.push(stored_file_receipt(
                file,
                message_id,
                ordinal,
                logical_path,
                resolved_path,
                now,
            ));
        }

        batches.push(StoredStartupContextBatch {
            id: prior_batch
                .map(|batch| batch.id.clone())
                .unwrap_or_else(|| crate::id::new_id("startup-batch")),
            kind: StoredStartupBatchKind::Initial,
            control_message_id,
            files: file_receipts,
            appended_at: now,
            delivery_state: StoredStartupBatchDeliveryState::Captured,
            first_dispatched_at: None,
            first_provider_accepted_at: None,
        });
    }

    let state = if blocked {
        StoredStartupContextState::Blocked
    } else if batches.is_empty() {
        StoredStartupContextState::Empty
    } else {
        StoredStartupContextState::Prepared
    };
    Ok((
        StoredStartupContextReceipt {
            schema_version: STARTUP_CONTEXT_RECEIPT_SCHEMA_VERSION,
            project,
            plan_revision: preparation.plan_revision(),
            state,
            batches,
            blocked_issues,
            pending_updates: Vec::new(),
            prepared_at: now,
            first_dispatched_at: None,
            first_provider_accepted_at: None,
            metadata_repair: None,
        },
        messages,
    ))
}

fn stored_file_receipt(
    file: &CapturedStartupFile,
    message_id: String,
    ordinal: u32,
    logical_path: String,
    resolved_path: String,
    now: DateTime<Utc>,
) -> StoredStartupFileReceipt {
    StoredStartupFileReceipt {
        spec_id: file.spec_id().to_string(),
        message_id,
        ordinal,
        logical_path,
        resolved_path,
        classification: file.classification().to_stored(),
        sha256: file.sha256().to_string(),
        bytes: file.bytes(),
        estimated_tokens: file.estimated_tokens(),
        latest_observation: StoredStartupFileObservation {
            observed_at: now,
            state: StoredStartupObservedState::Current,
        },
        last_notified_observation: None,
        notification_count: 0,
    }
}

fn startup_stored_message(id: String, content: Vec<ContentBlock>) -> StoredMessage {
    StoredMessage {
        id,
        role: Role::User,
        content,
        display_role: Some(StoredDisplayRole::System),
        timestamp: None,
        tool_duration_ms: None,
        token_usage: None,
    }
}

fn startup_file_metadata(
    ordinal: u32,
    logical_path: &str,
    resolved_path: &str,
    sha256: &str,
    bytes: u64,
) -> String {
    format!(
        "<jcode_project_file_read\n  ordinal=\"{ordinal}\"\n  path=\"{}\"\n  resolved_path=\"{}\"\n  sha256=\"{}\"\n  bytes=\"{bytes}\"\n  encoding=\"utf-8\"\n  completeness=\"full\"\n/>",
        xml_escape_attribute(logical_path),
        xml_escape_attribute(resolved_path),
        xml_escape_attribute(sha256),
    )
}

fn xml_escape_attribute(value: &str) -> String {
    let mut escaped = String::with_capacity(value.len());
    for character in value.chars() {
        match character {
            '&' => escaped.push_str("&amp;"),
            '<' => escaped.push_str("&lt;"),
            '>' => escaped.push_str("&gt;"),
            '"' => escaped.push_str("&quot;"),
            '\'' => escaped.push_str("&apos;"),
            _ => escaped.push(character),
        }
    }
    escaped
}

fn startup_utf8_path(
    path: &std::path::Path,
    label: &str,
) -> std::result::Result<String, StartupContextInstallError> {
    path.to_str().map(ToOwned::to_owned).ok_or_else(|| {
        StartupContextInstallError::InvalidPreparation {
            detail: format!(
                "captured startup {label} is not valid UTF-8: {}",
                path.display()
            ),
        }
    })
}

fn invalid_preparation(error: StartupContextError) -> StartupContextInstallError {
    StartupContextInstallError::InvalidPreparation {
        detail: error.to_string(),
    }
}

fn startup_message_ids(receipt: Option<&StoredStartupContextReceipt>) -> HashSet<&str> {
    let mut ids = HashSet::new();
    if let Some(receipt) = receipt {
        for batch in &receipt.batches {
            ids.insert(batch.control_message_id.as_str());
            ids.extend(batch.files.iter().map(|file| file.message_id.as_str()));
        }
    }
    ids
}

fn validate_existing_receipt_references(
    session: &Session,
) -> std::result::Result<(), StartupContextInstallError> {
    let Some(receipt) = session.startup_context.as_ref() else {
        return Ok(());
    };
    if receipt.schema_version != STARTUP_CONTEXT_RECEIPT_SCHEMA_VERSION {
        return Err(StartupContextInstallError::InvalidExistingReceipt {
            detail: format!("unsupported schema version {}", receipt.schema_version),
        });
    }
    let ids = startup_message_ids(Some(receipt));
    for id in ids {
        let matches = session
            .messages
            .iter()
            .filter(|message| message.id == id)
            .count();
        if matches != 1 {
            return Err(StartupContextInstallError::InvalidExistingReceipt {
                detail: format!("message reference {id} matched {matches} transcript messages"),
            });
        }
    }
    Ok(())
}

fn is_session_context_stored_message(message: &StoredMessage) -> bool {
    message.content.iter().any(|block| {
        matches!(
            block,
            ContentBlock::Text { text, .. }
                if text.starts_with(super::model::SESSION_CONTEXT_PREFIX)
        )
    })
}

